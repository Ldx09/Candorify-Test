"""Makes the backup translations of the question bank for every supported language:
data/question_bank_translations.json. The app uses them when Gemini is down or its reply fails a check.

    python -m scripts.translate_question_bank              # all languages
    python -m scripts.translate_question_bank --only es,ar  # just these

Needs GEMINI_API_KEY in .env. Only texts that changed since the last run are sent again.
Progress is printed and saved after each language, so you can stop (Ctrl+C) and run it again later.
Every translation must keep the same {placeholders} and numbers, or it is left out (English is used).
Review the output file before committing it.
"""
import argparse
import json
import re
import sys
from pathlib import Path

from app.questions.bank import BANK
from app.translation import gemini_client
from app.translation.languages import LANGUAGES
from app.translation.translator import _digits

OUT = Path(__file__).resolve().parents[1] / "data" / "question_bank_translations.json"
FIELDS = ("text", "text_no_date", "flag_message")
_PLACEHOLDER = re.compile(r"\{[a-z_]+\}")
TIMEOUT_SECONDS = 120  # one language is a big request; give Gemini time to answer


def english_items() -> dict[str, str]:
    """Flat {key: English text}, e.g. "types.room_nights.text", "choices.Not sure"."""
    items = {}
    for qt in BANK.questions:
        for field in FIELDS:
            if getattr(qt, field, None):
                items[f"types.{qt.id}.{field}"] = getattr(qt, field)
        for c in qt.choices or []:
            items[f"choices.{c}"] = c
    return items


def ok(source: str, text) -> bool:
    return (isinstance(text, str) and bool(text.strip())
            and sorted(_PLACEHOLDER.findall(text)) == sorted(_PLACEHOLDER.findall(source))
            and _digits(_PLACEHOLDER.sub("", text)) == _digits(_PLACEHOLDER.sub("", source)))


def prompt(texts: dict[str, str], lang_name: str) -> str:
    return (
        f"Translate each value in the JSON object below from English into {lang_name}. These are questions and "
        "messages a patient reads while checking their hospital bill: use short, friendly, plain wording.\n"
        "Rules:\n"
        "- Keep every placeholder in curly braces like {qty} or {description} exactly as written (do not translate it).\n"
        "- Keep every number exactly as written.\n"
        "- Keep the same keys. Translate only the values.\n"
        'Reply with JSON only in this shape: {"translations": {"<key>": "<translated text>"}}\n\n'
        f"{json.dumps(texts, ensure_ascii=False, indent=1)}"
    )


def get_entry(lang_data: dict, key: str) -> dict | None:
    section, *rest = key.split(".", 1)
    if section == "choices":
        return lang_data.get("choices", {}).get(rest[0])
    type_id, field = rest[0].split(".")
    return lang_data.get("types", {}).get(type_id, {}).get(field)


def set_entry(lang_data: dict, key: str, value: dict) -> None:
    section, *rest = key.split(".", 1)
    if section == "choices":
        lang_data.setdefault("choices", {})[rest[0]] = value
    else:
        type_id, field = rest[0].split(".")
        lang_data.setdefault("types", {}).setdefault(type_id, {})[field] = value


def save(data: dict) -> None:
    data["note"] = "Generated by scripts/translate_question_bank.py. 'source' is the English it was made from."
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def run(only: list[str] | None = None, client=None) -> dict:
    data = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    languages = data.setdefault("languages", {})
    source = english_items()
    summary = {}
    for lang in LANGUAGES:
        if lang.code == "en" or (only and lang.code not in only):
            continue
        lang_data = languages.setdefault(lang.code, {})
        todo = {k: v for k, v in source.items() if (get_entry(lang_data, k) or {}).get("source") != v}
        if not todo:
            summary[lang.code] = "up to date"
            print(f"{lang.code:6} up to date", flush=True)
            continue
        print(f"{lang.code:6} translating {len(todo)} texts...", end=" ", flush=True)
        try:
            reply = gemini_client.generate_json(prompt(todo, lang.name), client=client, timeout=TIMEOUT_SECONDS)
        except gemini_client.GeminiUnavailable as exc:
            summary[lang.code] = f"skipped ({exc})"
            print(summary[lang.code], flush=True)
            continue
        got = reply.get("translations") if isinstance(reply.get("translations"), dict) else {}
        good = 0
        for k, src in todo.items():
            if ok(src, got.get(k)):
                set_entry(lang_data, k, {"source": src, "text": got[k].strip()})
                good += 1
        summary[lang.code] = f"{good}/{len(todo)} translated" + ("" if good == len(todo) else " (rest stay English)")
        print(summary[lang.code], flush=True)
        save(data)  # saved after every language, so stopping early (Ctrl+C) keeps what's done
    save(data)
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", help="comma-separated language codes, e.g. es,ar,zh")
    args = parser.parse_args()
    only = [c.strip() for c in args.only.split(",")] if args.only else None
    run(only)
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())